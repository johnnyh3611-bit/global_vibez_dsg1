export const getGameById = (id: string | undefined | null): GameRegistryEntry | undefined => {
  if (!id) return undefined;
  return GAMES.find((g) => g.id === id.toLowerCase());
};

export const getGameName = (id: string | undefined | null): string => {
  return getGameById(id)?.name ?? (id ? id.replace(/_/g, ' ').replace(/\b\w/g, (l) => l.toUpperCase()) : 'Unknown Game');
};

export const getClientGameIds = (): string[] => GAMES.filter((g) => g.mode === 'client').map((g) => g.id);

export const getListedGames = (): GameRegistryEntry[] => GAMES.filter((g) => g.listed);

export const getGamesByCategory = (category: GameCategory): GameRegistryEntry[] =>
  GAMES.filter((g) => g.category === category);
