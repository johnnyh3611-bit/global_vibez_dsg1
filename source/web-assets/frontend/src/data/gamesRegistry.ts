/**
 * gamesRegistry - single source of truth for Practice Mode metadata.
 *
 * Why this exists:
 *   - `PracticeMode.tsx` and `PracticeGamePlay.tsx` were each maintaining
 *     parallel hard-coded lists of game names, categories, client/server mode,
 *     and display metadata. Those lists drifted (wrong counts, missing
 *     games, inconsistent client-side flags).
 *   - This file is the canonical place to add, remove, or re-categorize a
 *     practice game. Every UI surface should read from it.
 */

export type GameCategory = 'board' | 'card' | 'casino' | 'arcade' | 'social';
export type GameMode = 'client' | 'server';

